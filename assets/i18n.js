const LANG_KEY = "nica_lang";

function getLang() {
  return localStorage.getItem(LANG_KEY) || "es";
}

function setLang(lang) {
  localStorage.setItem(LANG_KEY, lang);
}

function t(key) {
  const lang = getLang();
  return TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS["es"]?.[key] ?? key;
}

function applyTranslations() {
  const lang = getLang();
  document.documentElement.lang = lang;

  /* Texto simple */
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const val = TRANSLATIONS[lang]?.[el.dataset.i18n];
    if (val !== undefined) el.textContent = val;
  });

  /* innerHTML (permite <span> anidados) */
  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    const val = TRANSLATIONS[lang]?.[el.dataset.i18nHtml];
    if (val !== undefined) el.innerHTML = val;
  });

  /* Placeholder */
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    const val = TRANSLATIONS[lang]?.[el.dataset.i18nPh];
    if (val !== undefined) el.placeholder = val;
  });

  /* aria-label */
  document.querySelectorAll("[data-i18n-aria]").forEach(el => {
    const val = TRANSLATIONS[lang]?.[el.dataset.i18nAria];
    if (val !== undefined) el.setAttribute("aria-label", val);
  });

  /* Botón de idioma */
  const toggle = document.getElementById("langToggle");
  if (toggle) {
    const lbl = toggle.querySelector(".lang-label");
    if (lbl) lbl.textContent = lang === "es" ? "EN" : "ES";
    toggle.title = lang === "es" ? "Switch to English" : "Cambiar a Español";
    toggle.setAttribute("aria-label", TRANSLATIONS[lang]["lang.toggle_label"] || "");
  }

  /* Copyright */
  const yr = new Date().getFullYear();
  const copy = lang === "es"
    ? `© ${yr} Nicamerica Import Corp. Todos los derechos reservados.`
    : `© ${yr} Nicamerica Import Corp. All rights reserved.`;
  document.querySelectorAll(".copyright").forEach(el => { el.textContent = copy; });
}

function toggleLang() {
  setLang(getLang() === "es" ? "en" : "es");
  applyTranslations();
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang: getLang() } }));
}

document.addEventListener("DOMContentLoaded", applyTranslations);

window.i18n = { t, getLang, setLang, toggleLang, applyTranslations, TRANSLATIONS };
